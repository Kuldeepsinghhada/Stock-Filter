let currentLang = 'de';
let currentTab = 'home';

document.addEventListener('DOMContentLoaded', () => {
  initNavigation();
  initLanguageToggle();
  initFilterPills();
  renderApp();
});

function initNavigation() {
  const navBtns = document.querySelectorAll('.nav-item');
  navBtns.forEach(btn => {
    btn.addEventListener('click', () => {
      const pageId = btn.getAttribute('data-tab');
      switchTab(pageId);
    });
  });
}

function initFilterPills() {
  document.addEventListener('click', (e) => {
    if (e.target.classList.contains('tab-pill')) {
      const parent = e.target.parentElement;
      parent.querySelectorAll('.tab-pill').forEach(p => p.classList.remove('active'));
      e.target.classList.add('active');
      const filterName = e.target.textContent;
      filterCampaignsByStatus(e.target.getAttribute('data-status'));
    }
  });
}

function filterCampaignsByStatus(status) {
  const cards = document.querySelectorAll('.campaign-item-card');
  cards.forEach(card => {
    const cardStatus = card.getAttribute('data-status');
    if (!status || status === 'all' || cardStatus === status) {
      card.style.display = 'block';
    } else {
      card.style.display = 'none';
    }
  });
}

function switchTab(tabId) {
  currentTab = tabId;
  document.querySelectorAll('.nav-item').forEach(b => b.classList.remove('active'));
  document.querySelectorAll('.screen-page').forEach(p => p.classList.remove('active'));

  const activeBtn = document.querySelector(`.nav-item[data-tab="${tabId}"]`);
  const activePage = document.getElementById(`page-${tabId}`);

  if (activeBtn) activeBtn.classList.add('active');
  if (activePage) activePage.classList.add('active');

  const titleEl = document.getElementById('current-screen-name');
  if (titleEl) {
    const titleKeys = {
      home: 'home_title',
      campaigns: 'campaigns_title',
      recruiting: 'recruiting_title',
      analytics: 'analytics_title',
      billing: 'billing_title'
    };
    const key = titleKeys[tabId] || 'home_title';
    titleEl.setAttribute('data-i18n', key);
    titleEl.textContent = translations[currentLang][key];
  }

  const container = document.querySelector('.screen-scroll-container');
  if (container) container.scrollTop = 0;
}

function initLanguageToggle() {
  const toggleBtn = document.getElementById('lang-toggle');
  if (toggleBtn) {
    toggleBtn.addEventListener('click', () => {
      currentLang = currentLang === 'de' ? 'en' : 'de';
      renderApp();
      showToast(currentLang === 'de' ? 'Sprache auf Deutsch geändert 🇩🇪' : 'Language changed to English 🇬🇧');
    });
  }
}

function renderApp() {
  const langData = translations[currentLang];
  
  const langLabel = document.getElementById('lang-label');
  if (langLabel) {
    langLabel.textContent = currentLang === 'de' ? 'DE 🇩🇪' : 'EN 🇬🇧';
  }

  const titleEl = document.getElementById('current-screen-name');
  if (titleEl) {
    const key = titleEl.getAttribute('data-i18n');
    if (key && langData[key]) {
      titleEl.textContent = langData[key];
    }
  }

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (langData[key]) {
      el.textContent = langData[key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (langData[key]) {
      el.setAttribute('placeholder', langData[key]);
    }
  });
}

function showToast(msg) {
  let toast = document.getElementById('app-toast');
  if (!toast) {
    toast = document.createElement('div');
    toast.id = 'app-toast';
    toast.className = 'toast-msg';
    document.querySelector('.device-container').appendChild(toast);
  }
  toast.textContent = msg;
  toast.classList.add('show');
  setTimeout(() => {
    toast.classList.remove('show');
  }, 2200);
}

function triggerAction(actionName) {
  const msgs = {
    de: `Aktion „${actionName}“ ausgeführt!`,
    en: `Action "${actionName}" executed!`
  };
  showToast(msgs[currentLang]);
}
